import { attr, blank, block, expr, renderFile, str, tpl, type Block } from "./hcl.js";
import { LAMBDA_ROLE_SUFFIX, resolveNames, type ResolvedResource } from "./names.js";
import { stubFor } from "./runtimes.js";
import type { InputSpec } from "./schema.js";

const HEADER = "# Generated by opentofu-generator. Do not edit by hand.";

function baseBlocks(input: InputSpec): Block[] {
  return [
    block("terraform", [], [
      attr("required_version", str(">= 1.8.0")),
      blank,
      block("required_providers", [], [
        attr("aws", { source: str("hashicorp/aws"), version: str("~> 6.0") }),
        attr("archive", { source: str("hashicorp/archive"), version: str("~> 2.7") }),
      ]),
    ]),
    block("provider", ["aws"], [attr("region", str(input.region))]),
    block("data", ["aws_caller_identity", "current"]),
    block("data", ["aws_partition", "current"]),
  ];
}

// S3 bucket names are global across every AWS account. Suffixing the account
// id and region keeps them unique without any randomness in the output.
function objectStore(r: ResolvedResource, region: string): Block[] {
  return [
    block("resource", ["aws_s3_bucket", r.label], [
      attr("bucket", tpl(`${r.awsName}-\${data.aws_caller_identity.current.account_id}-${region}`)),
      attr("force_destroy", true),
      blank,
      attr("tags", { Name: str(r.tagName) }),
    ]),
  ];
}

function queue(r: ResolvedResource): Block[] {
  return [
    block("resource", ["aws_sqs_queue", r.label], [
      attr("name", str(r.awsName)),
      blank,
      attr("tags", { Name: str(r.tagName) }),
    ]),
  ];
}

function lambda(r: ResolvedResource, runtime: string): Block[] {
  const stub = stubFor(runtime);
  const l = r.label;
  return [
    block("data", ["archive_file", l], [
      attr("type", str("zip")),
      attr("output_path", tpl(`\${path.module}/build/${r.awsName}.zip`)),
      blank,
      block("source", [], [attr("filename", str(stub.filename)), attr("content", str(stub.source))]),
    ]),
    block("resource", ["aws_iam_role", l], [
      attr("name", str(`${r.awsName}${LAMBDA_ROLE_SUFFIX}`)),
      attr("assume_role_policy", expr("data.aws_iam_policy_document.lambda_assume_role.json")),
      blank,
      attr("tags", { Name: str(r.tagName) }),
    ]),
    block("resource", ["aws_iam_role_policy_attachment", l], [
      attr("role", expr(`aws_iam_role.${l}.name`)),
      attr(
        "policy_arn",
        tpl("arn:${data.aws_partition.current.partition}:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole"),
      ),
    ]),
    // Lambda creates this log group on first invoke if it does not exist, and
    // then `tofu destroy` would leave it behind. Owning it keeps teardown clean.
    block("resource", ["aws_cloudwatch_log_group", l], [
      attr("name", str(`/aws/lambda/${r.awsName}`)),
      attr("retention_in_days", 7),
      blank,
      attr("tags", { Name: str(r.tagName) }),
    ]),
    block("resource", ["aws_lambda_function", l], [
      attr("function_name", str(r.awsName)),
      attr("role", expr(`aws_iam_role.${l}.arn`)),
      attr("runtime", str(runtime)),
      attr("handler", str(stub.handler)),
      attr("filename", expr(`data.archive_file.${l}.output_path`)),
      attr("source_code_hash", expr(`data.archive_file.${l}.output_base64sha256`)),
      blank,
      attr("tags", { Name: str(r.tagName) }),
      blank,
      attr("depends_on", [
        expr(`aws_iam_role_policy_attachment.${l}`),
        expr(`aws_cloudwatch_log_group.${l}`),
      ]),
    ]),
  ];
}

function lambdaAssumeRolePolicy(): Block {
  return block("data", ["aws_iam_policy_document", "lambda_assume_role"], [
    block("statement", [], [
      attr("effect", str("Allow")),
      attr("actions", [str("sts:AssumeRole")]),
      blank,
      block("principals", [], [
        attr("type", str("Service")),
        attr("identifiers", [str("lambda.amazonaws.com")]),
      ]),
    ]),
  ]);
}

export function generate(input: InputSpec): string {
  const resolved = resolveNames(input);
  const blocks = baseBlocks(input);

  if (resolved.some((r) => r.spec.type === "function")) blocks.push(lambdaAssumeRolePolicy());

  for (const r of resolved) {
    switch (r.spec.type) {
      case "object-store":
        blocks.push(...objectStore(r, input.region));
        break;
      case "queue":
        blocks.push(...queue(r));
        break;
      case "function":
        blocks.push(...lambda(r, r.spec.runtime));
        break;
    }
  }

  return renderFile(blocks, HEADER);
}
